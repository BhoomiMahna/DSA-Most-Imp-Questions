class Solution {
public:
    long long countCommas(long long n) {
        long long k = 0;

        if(n >= 1000 && n < 1000000){
            k = n - 1000 + 1;
        }

        else if(n >= 1000000 && n < 1000000000){
            k = 2*(n - 1000 +1) -999999 + 999;
        }

        else if(n >= 1000000000 && n < 1000000000000){
            k = 3*(n -1000+1) -999999999 -999999 + 1998;
        }

        else if(n >= 1000000000000 && n < 1000000000000000){
            k = 4*(n -1000 +1)- 999999999999 -999999999 -999999 + 2997;
        }

        else if(n == 1000000000000000){
            k = 5*(n -1000 +1)-999999999999999
                - 999999999999 -999999999 -999999 + 3996;
        }

        return k;
    }
};